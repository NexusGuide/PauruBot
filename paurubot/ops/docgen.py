"""Reference docs generated from the source (QA-03).

    python -m paurubot.ops.docgen          # rewrite docs/reference/*.md
    python -m paurubot.ops.docgen --check  # exit 1 when a file is out of date (used by the tests)

Every table here is read from the code itself (settings specs, the role matrix, the HTTP routes,
the CLI and installer commands), so the reference cannot drift from what the program does.
"""

from __future__ import annotations

import inspect
import json
import re
import sys
from collections.abc import Callable, Iterator
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "reference"
HEADER = "<!-- Generated by `python -m paurubot.ops.docgen`. Edit the source, not this file. -->\n\n"


def _labels() -> dict[str, str]:
    path = ROOT / "frontend" / "src" / "admin" / "locales" / "en.json"
    try:
        data: dict[str, str] = json.loads(path.read_text(encoding="utf-8"))
    except OSError:
        return {}
    return data


def _cell(value: object) -> str:
    text = str(value).replace("|", "\\|").replace("\n", " ")
    return text or "—"


def _table(head: list[str], rows: list[list[object]]) -> str:
    lines = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    lines += ["| " + " | ".join(_cell(c) for c in row) + " |" for row in rows]
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------- settings


def settings_doc() -> str:
    from paurubot.core.settings import SPECS

    labels = _labels()
    groups: dict[str, list[str]] = {}
    for key, spec in SPECS.items():
        groups.setdefault(spec.group, []).append(key)
    out = [
        "# Shop settings\n\n",
        "Each shop's settings, changed in the admin panel under Settings (appearance ones on the Bot menu ",
        "screen) or through `PUT /api/admin/settings`. Secret values are stored encrypted and never returned.\n",
    ]
    for group, keys in groups.items():
        title = labels.get(f"settings_group_{group}", group.title())
        out.append(f"\n## {title}\n\n")
        rows: list[list[object]] = []
        for key in keys:
            spec = SPECS[key]
            default = spec.default
            shown = (
                ""
                if spec.secret
                else (json.dumps(default, ensure_ascii=False) if default is not None else "")
            )
            label = labels.get(f"setting_{key}", "")
            hint = labels.get(f"setting_{key}_hint", "")
            about = f"{label}. {hint}".strip(". ") if hint else label
            rows.append([f"`{key}`", spec.kind.__name__ + (" (secret)" if spec.secret else ""), shown, about])
        out.append(_table(["Key", "Type", "Default", "Meaning"], rows))
    return "".join(out)


# ---------------------------------------------------------------- roles


def roles_doc() -> str:
    from paurubot.auth import rbac
    from paurubot.db.models import StaffRole

    labels = _labels()
    roles = [r for r in StaffRole if r in rbac.MATRIX]
    head = ["Permission", "Meaning", *[labels.get(f"role_{r.value}", r.value) for r in roles]]
    rows: list[list[object]] = []
    for permission in rbac.PERMISSIONS:
        meaning = labels.get(f"perm_{permission.replace('.', '_')}", "")
        rows.append(
            [f"`{permission}`", meaning, *["yes" if permission in rbac.MATRIX[r] else "" for r in roles]]
        )
    return (
        "# Roles and permissions\n\n"
        "What each staff role may do. Resellers are always limited to their own customers and services, "
        "and may only be given these permissions: "
        + ", ".join(f"`{p}`" for p in sorted(rbac.SCOPED_FOR_RESELLER))
        + ". API keys never carry `staff.manage`, `panels.secrets` or `backups.manage`.\n\n"
        + _table(head, rows)
    )


# ---------------------------------------------------------------- HTTP API


def _permissions(call: Callable[..., Any] | None, dependant: Any) -> Iterator[str]:
    permission = getattr(call, "permission", None)
    if permission:
        yield str(permission)
    for child in getattr(dependant, "dependencies", []):
        yield from _permissions(child.call, child)


def _access(path: str, permissions: list[str]) -> str:
    if permissions:
        return ", ".join(f"`{p}`" for p in sorted(set(permissions)))
    if path.startswith(("/api/admin", "/api/auth/api-keys", "/api/auth/me", "/api/auth/password")):
        return "staff session"
    for start, label in (
        ("/api/webapp", "Mini App initData"),
        ("/api/pay/", "gateway callback, verified with the provider"),
        ("/api/telegram/", "Telegram secret token"),
        ("/api/webhooks/", "panel webhook secret"),
        ("/api/setup/complete", "one-time setup token"),
        ("/api/auth/logout", "staff session"),
        ("/s/", "subscription token in the link"),
        ("/metrics", "METRICS_TOKEN or a private network"),
    ):
        if path.startswith(start):
            return label
    return "public"


def _routes(routes: list[Any], prefix: str = "") -> Iterator[tuple[str, Any]]:
    """Flatten included routers (newer FastAPI keeps them nested) into (full path, APIRoute)."""
    from fastapi.routing import APIRoute

    for route in routes:
        if isinstance(route, APIRoute):
            yield prefix + route.path, route
        elif hasattr(route, "original_router"):
            extra = getattr(getattr(route, "include_context", None), "prefix", "") or ""
            yield from _routes(list(route.original_router.routes), prefix + extra)


STATIC = {"/", "/admin", "/app"}


def api_doc() -> str:
    from paurubot.api.app import create_app

    app = create_app()
    sections: dict[str, list[list[object]]] = {}
    for path, route in _routes(list(app.routes)):
        if path in STATIC or path.startswith(("/admin/", "/app/", "/s/_/")):
            continue  # the built web apps and their assets
        permissions = list(_permissions(None, route.dependant))
        summary = inspect.getdoc(route.endpoint) or ""
        first = summary.split("\n", 1)[0] or route.endpoint.__name__.strip("_").replace("_", " ").capitalize()
        parts = path.split("/")
        area = "/".join(parts[:3]) if path.startswith("/api/") else "/" + (parts[1] if len(parts) > 1 else "")
        for method in sorted(route.methods - {"HEAD", "OPTIONS"}):
            sections.setdefault(area, []).append([method, f"`{path}`", _access(path, permissions), first])
    out = [
        "# HTTP API\n\n",
        "Every route the server answers, with who may call it. Staff routes accept the admin panel's session ",
        "cookie (with the CSRF header on writes) or a personal API key as `Authorization: Bearer pbk_...`; ",
        "read-only keys can only use GET.\n",
    ]
    for area in sorted(sections):
        out.append(f"\n## `{area}`\n\n")
        rows = sorted(sections[area], key=lambda r: (str(r[1]), str(r[0])))
        out.append(_table(["Method", "Path", "Access", "What it does"], rows))
    return "".join(out)


# ---------------------------------------------------------------- command line


def cli_doc() -> str:
    from paurubot.cli.main import COMMANDS, build_parser

    build_parser()  # registers the commands
    installer = (ROOT / "install.sh").read_text(encoding="utf-8")
    block = installer[installer.find("\nmain() {") :]
    actions = re.findall(r"^\s{4}([a-z][a-z-]*)\)", block, re.M)
    usage = [line[2:] for line in installer.splitlines()[1:14] if line.startswith("#   ")]
    out = [
        "# Command line\n\n",
        "## Server manager (`pauru`)\n\n",
        "The installer links itself as `/usr/local/bin/pauru`. Run it as root; without arguments it opens a menu.\n\n",
        "```\n" + "\n".join(u.strip() for u in usage) + "\n```\n\n",
        "Actions: " + ", ".join(f"`{a}`" for a in actions if a not in {"menu", "-h"}) + ".\n\n",
        "## Application (`paurubot`)\n\n",
        "Run inside a container, for example `docker compose exec api paurubot doctor`.\n\n",
        _table(["Command", "What it does"], [[f"`{n}`", h] for n, (_, h, _c) in sorted(COMMANDS.items())]),
    ]
    return "".join(out)


DOCS: dict[str, Callable[[], str]] = {
    "settings.md": settings_doc,
    "roles.md": roles_doc,
    "api.md": api_doc,
    "cli.md": cli_doc,
}


def render() -> dict[str, str]:
    return {name: HEADER + build() for name, build in DOCS.items()}


def main(argv: list[str]) -> int:
    rendered = render()
    stale = [
        n for n, text in rendered.items() if not (OUT / n).is_file() or (OUT / n).read_text("utf-8") != text
    ]
    if "--check" in argv:
        for name in stale:
            print(f"docs/reference/{name} is out of date; run python -m paurubot.ops.docgen")
        return 1 if stale else 0
    OUT.mkdir(parents=True, exist_ok=True)
    for name in stale:
        (OUT / name).write_text(rendered[name], encoding="utf-8")
        print(f"wrote docs/reference/{name}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
