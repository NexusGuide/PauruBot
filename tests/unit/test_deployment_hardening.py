"""Deployment hardening from the November audit (AUD-11, AUD-12, AUD-13).

- Redis held staff sessions, login locks and leases with no password: any container on the
  compose network could read or forge them. It now requires one, generated by the installer.
- Caddy had no healthcheck, so a dead proxy went unnoticed.
- Third-party GitHub Actions ran by moving tag in a workflow that can push and sign images;
  they are pinned to commits (dependabot keeps the pins current).
"""

from __future__ import annotations

import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]


def _compose() -> dict:  # type: ignore[type-arg]
    return yaml.safe_load((ROOT / "docker-compose.yml").read_text())


def test_redis_requires_a_password_everyone_shares() -> None:
    services = _compose()["services"]
    redis = services["redis"]
    command = " ".join(redis["command"])
    assert "--requirepass ${REDIS_PASSWORD:?set REDIS_PASSWORD}" in command
    assert "REDISCLI_AUTH" in " ".join(redis["healthcheck"]["test"])
    assert "ports" not in redis  # still only on the compose network
    for name in ("api", "bot", "worker", "migrate"):
        url = services[name]["environment"]["REDIS_URL"]
        assert url == "redis://:${REDIS_PASSWORD:?set REDIS_PASSWORD}@redis:6379/0", name
    installer = (ROOT / "install.sh").read_text()
    assert "REDIS_PASSWORD=$(random_secret 32 32)" in installer  # a fresh install
    assert (
        '[[ -n $(env_get REDIS_PASSWORD) ]] || env_set REDIS_PASSWORD "$(random_secret 32 32)"' in installer
    )
    assert "REDIS_PASSWORD=" in (ROOT / ".env.example").read_text()


def test_the_proxy_has_a_healthcheck() -> None:
    caddy = _compose()["services"]["caddy"]
    assert "healthcheck" in caddy and caddy["healthcheck"]["test"]


def test_third_party_actions_are_pinned_to_commits() -> None:
    for path in sorted((ROOT / ".github" / "workflows").glob("*.yml")):
        for line in path.read_text().splitlines():
            match = re.search(r"uses:\s*(\S+)", line)
            if not match or match.group(1).startswith("./"):
                continue
            ref = match.group(1)
            assert re.fullmatch(r"[\w.-]+/[\w./-]+@[0-9a-f]{40}", ref), f"{path.name}: {ref}"
            assert re.search(r"#\s*v\d", line), f"{path.name}: say which version {ref} is"
